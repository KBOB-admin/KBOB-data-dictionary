@dataclass
class Finding:
    level: str
    code: str
    message: str
    sheet: str | None = None
    cell: str | None = None
    row: int | None = None


class Validator:
    def __init__(self, workbook_path: Path):
        self.workbook_path = workbook_path
        self.findings: list[Finding] = []
        self.normalizations: list[dict] = []
        self.wb = openpyxl.load_workbook(workbook_path, data_only=True)
        self.dd = None
        self.ifc_uri_set = None
        self.ifc_object_type_pairs = None
        self.qudt_unit_labels = None
        self.dd_loaded = False
        self.ifc_uri_set_loaded = False

    def export_autogenerated_workbook(self, output_path: Path) -> Path:
        export_wb = openpyxl.load_workbook(self.workbook_path)
        for normalization in self.normalizations:
            if not normalization.get('safe_auto_normalization', False):
                continue
            sheet_name = normalization.get('sheet')
            row_idx = normalization.get('row')
            column_label = normalization.get('column')
            normalized_value = normalization.get('normalized_value')
            if not sheet_name or row_idx is None or not column_label:
                continue
            if normalized_value is None:
                continue
            if sheet_name not in export_wb.sheetnames:
                continue
            ws = export_wb[sheet_name]
            if sheet_name in {'Header', 'Dictionary_public'}:
                applied = False
                for r in range(2, ws.max_row + 1):
                    field_name = ws.cell(r, 1).value
                    if field_name is None:
                        continue
                    if str(field_name).strip() == str(column_label).strip():
                        ws.cell(r, 2).value = normalized_value
                        applied = True
                        break
                if not applied:
                    continue
            else:
                headers = self._sheet_headers(sheet_name)
                col_idx = headers.get(column_label)
                if not col_idx:
                    continue
                ws.cell(row_idx, col_idx).value = normalized_value
        output_path.parent.mkdir(parents=True, exist_ok=True)
        export_wb.save(output_path)
        return output_path

    def default_output_workbook_path(self, base_dir: Path | None = None) -> Path:
        root = base_dir or self.workbook_path.parent
        stamp = datetime.utcnow().strftime('%Y-%m-%d')
        return root / f'{self.workbook_path.stem}_validated{stamp}.xlsx'

    @staticmethod
    def _row_has_meaningful_content(row) -> bool:
        meaningful = []
        for v in row:
            if v is None:
                continue
            s = str(v).strip()
            if not s:
                continue
            meaningful.append(s)
        if not meaningful:
            return False
        joined = ' '.join(meaningful).lower()
        guidance_markers = [
            'should reference', 'should match', 'fill if', 'leave empty', 'required human label',
            'required canonical', 'validator should', 'reference-based validation target',
            'list-based validation', 'object columns: x = assigned', 'override values must match',
            'system generated', 'optional external', 'required registered source code', 'required; valid',
            'required de label', 'required en/canonical label', 'recommended de definition',
            'recommended en definition', 'official ifc property uri', 'official ifc set reference',
            'guid/uri: if applicable', 'objekt-id: system generated', 'bezeichnung: required',
            'designation: required', 'document identification: optional', 'dokument uri: optional',
            'dokument name: required', 'revision: recommended', 'owner: recommended',
            'documentcode: optional',
        ]
        if any(marker in joined for marker in guidance_markers):
            return False
        if len(meaningful) == 1:
            token = meaningful[0].lower()
            if token.startswith('http://') or token.startswith('https://'):
                return False
        return True

    def _iter_data_rows(self, ws, min_row: int):
        for idx, row in enumerate(ws.iter_rows(min_row=min_row, values_only=True), start=min_row):
            if not self._row_has_meaningful_content(row):
                continue
            meaningful = [str(v).strip() for v in row if v is not None and str(v).strip()]
            if meaningful and all(v.startswith('http://') or v.startswith('https://') for v in meaningful):
                continue
            yield idx, row

    def get_dd(self):
        if self.dd is None:
            self.dd = load_dd(self.workbook_path)
            self.dd_loaded = True
        return self.dd

    def get_ifc_uri_set(self) -> set[str]:
        if self.ifc_uri_set is None:
            self.ifc_uri_set = self._load_ifc_uri_set()
            self.ifc_uri_set_loaded = True
        return self.ifc_uri_set

    def get_ifc_object_type_pairs(self) -> dict[str, str]:
        if self.ifc_object_type_pairs is None:
            self.ifc_object_type_pairs = self._load_ifc_object_type_pairs()
        return self.ifc_object_type_pairs

    def get_qudt_unit_labels(self) -> dict[str, dict[str, set[str]]]:
        if self.qudt_unit_labels is None:
            self.qudt_unit_labels = self._load_qudt_unit_labels()
        return self.qudt_unit_labels

    def has_public_dictionary(self) -> bool:
        return 'Dictionary_public' in self.wb.sheetnames

    @staticmethod
    def _normalize_predefined_type(value: str | None) -> str | None:
        if not value:
            return None
        normalized = str(value).strip().replace(' ', '').replace('-', '_')
        return normalized.upper() if normalized else None

    def _extract_ifc_class_from_uri(self, ifc_uri: str | None) -> str | None:
        if not ifc_uri or '/class/' not in ifc_uri:
            return None
        tail = ifc_uri.split('/class/', 1)[1].strip()
        return self._extract_base_ifc_entity(tail)

    def _extract_base_ifc_entity(self, ifc_entity: str | None) -> str | None:
        if not ifc_entity or not str(ifc_entity).strip().startswith('Ifc'):
            return None
        candidate = str(ifc_entity).strip()
        ifc_uri_set = self.get_ifc_uri_set()
        candidate_uri = f'https://identifier.buildingsmart.org/uri/buildingsmart/ifc/4.3/class/{candidate}'
        if not ifc_uri_set or candidate_uri in ifc_uri_set:
            return candidate
        normalized = candidate.upper()
        for uri in ifc_uri_set:
            if '/class/' not in uri:
                continue
            tail = uri.split('/class/', 1)[1]
            if tail.upper() == normalized and tail.startswith('Ifc'):
                return tail
            if tail.startswith(candidate) and len(tail) > len(candidate):
                suffix = tail[len(candidate):]
                if suffix == suffix.upper() and any(ch.isalpha() for ch in suffix):
                    return candidate
        m = re.match(r'^(Ifc[A-Za-z]+)', candidate)
        return m.group(1) if m else candidate

    def validate_predefined_type(self, ifc_obj: str | None, predefined: str | None, ifc_uri: str | None, sheet_name: str, row_idx: int):
        if not predefined:
            return
        normalized_predefined = self._normalize_predefined_type(predefined)
        if not normalized_predefined or str(predefined).strip() == 'USERDEFINED':
            return
        ifc_uri_set = self.get_ifc_uri_set()
        if not ifc_obj:
            self.add('warning', 'predefined_type_without_ifc_entity', f'PredefinedType is filled but IfcObject Entity is missing, so authoritative validation cannot be completed: {predefined}', sheet=sheet_name, row=row_idx)
            return
        base_ifc_obj = self._extract_base_ifc_entity(ifc_obj) or ifc_obj
        candidate_uri = f'https://identifier.buildingsmart.org/uri/buildingsmart/ifc/4.3/class/{base_ifc_obj}{normalized_predefined}'
        if ifc_uri_set and candidate_uri not in ifc_uri_set:
            self.add('error', 'invalid_predefined_type', f'PredefinedType {predefined} is not a valid authoritative IFC predefined type for {base_ifc_obj}', sheet=sheet_name, row=row_idx)
            return
        derived_ifc_class = self._extract_ifc_class_from_uri(ifc_uri)
        if derived_ifc_class and not str(derived_ifc_class).startswith(str(base_ifc_obj)):
            self.add('error', 'ifc_uri_entity_mismatch', f'IFC URI implies base IFC class {derived_ifc_class}, but IfcObject Entity is {ifc_obj}', sheet=sheet_name, row=row_idx)
            return
        if ifc_uri and ifc_uri != candidate_uri:
            self.add('error', 'ifc_uri_predefined_mismatch', f'IFC URI {ifc_uri} does not match the authoritative IFC predefined-type URI implied by IfcObject Entity + PredefinedType: {candidate_uri}', sheet=sheet_name, row=row_idx)

    def validate_ifc_object_type_pair(self, ifc_obj: str | None, ifc_type: str | None, sheet_name: str, row_idx: int):
        if not ifc_type:
            return
        ifc_object_type_pairs = self.get_ifc_object_type_pairs()
        if not ifc_object_type_pairs:
            return
        base_ifc_obj = self._extract_base_ifc_entity(ifc_obj)
        expected_ifc_type = ifc_object_type_pairs.get(base_ifc_obj) if base_ifc_obj else None
        if not expected_ifc_type:
            self.add('error', 'invalid_ifc_type_object_entity', f'IfcTypeObject Entity is filled, but {ifc_obj or "the empty IfcObject Entity"} has no corresponding IFC 4.3 TypeObject entity.', sheet=sheet_name, row=row_idx)
        elif ifc_type != expected_ifc_type:
            self.add('error', 'invalid_ifc_object_type_pair', f'IfcTypeObject Entity must match IfcObject Entity. For {base_ifc_obj}, the schema-conformant type entity is {expected_ifc_type}. Got: {ifc_type}', sheet=sheet_name, row=row_idx)

    @staticmethod
    def _is_non_ifc_taxonomy_class(category: str | None, provenance: str | None) -> bool:
        category_text = str(category or '').strip().casefold()
        provenance_text = str(provenance or '').strip().casefold()
        return 'document type taxonomy' in category_text or 'dokumenttypenkatalog' in provenance_text

    def add(self, level: str, code: str, message: str, sheet: str | None = None, cell: str | None = None, row: int | None = None):
        self.findings.append(Finding(level, code, message, sheet, cell, row))

    def add_normalization(self, sheet: str, row: int | None, column: str | None, original_value, normalized_value, reason: str, normalization_kind: str, safe_auto_normalization: bool = True):
        self.normalizations.append({
            'sheet': sheet,
            'row': row,
            'column': column,
            'original_value': original_value,
            'normalized_value': normalized_value,
            'reason': reason,
            'normalization_kind': normalization_kind,
            'safe_auto_normalization': safe_auto_normalization,
        })

    @staticmethod
    def _normalize_label(value: str | None) -> str | None:
        if value is None:
            return None
        s = str(value).strip()
        if not s:
            return None
        return re.sub(r'\s+', ' ', s).strip().casefold()

    def _load_qudt_unit_labels(self) -> dict[str, dict[str, set[str]]]:
        labels_by_uri: dict[str, dict[str, set[str]]] = {}
        if not QUDT_UNITS_TTL.exists():
            self.add('warning', 'qudt_reference_missing', f'QUDT units ontology not found: {QUDT_UNITS_TTL}')
            return labels_by_uri
        try:
            g = rdflib.Graph()
            g.parse(QUDT_UNITS_TTL, format='turtle')
            query = """
            PREFIX rdfs: <http://www.w3.org/2000/01/rdf-schema#>
            SELECT ?unit ?label WHERE {
              ?unit rdfs:label ?label .
            }
            """
            for row in g.query(query):
                uri = str(row.unit)
                label = row.label
                lang = (label.language or '').lower()
                if lang.startswith('en'):
                    lang_key = 'en'
                elif lang.startswith('de'):
                    lang_key = 'de'
                elif lang.startswith('fr'):
                    lang_key = 'fr'
                elif lang.startswith('it'):
                    lang_key = 'it'
                else:
                    continue
                labels_by_uri.setdefault(uri, {}).setdefault(lang_key, set()).add(self._normalize_label(str(label)))
        except Exception as e:
            self.add('warning', 'qudt_reference_load_failed', f'Failed to load QUDT units ontology {QUDT_UNITS_TTL}: {e}')
        return labels_by_uri

    def _load_ifc_uri_set(self) -> set[str]:
        if BSDD_URI_CACHE.exists():
            try:
                payload = json.loads(BSDD_URI_CACHE.read_text())
                return set(payload.get('uris', []))
            except Exception:
                pass
        self.add('warning', 'bsdd_reference_missing', f'bSDD URI cache not found: {BSDD_URI_CACHE}')
        return set()

    def _load_ifc_object_type_pairs(self) -> dict[str, str]:
        if IFC_OBJECT_TYPE_PAIRS.exists():
            try:
                payload = json.loads(IFC_OBJECT_TYPE_PAIRS.read_text())
                return dict(payload.get('object_type_pairs', {}))
            except Exception:
                pass
        self.add('warning', 'ifc_entity_reference_missing', f'IFC object/type entity reference not found: {IFC_OBJECT_TYPE_PAIRS}')
        return {}

    def _load_rules_multilingual_lookup(self, canonical_header: str, translations: list[tuple[str, str]]) -> tuple[dict[str, str], dict[str, dict[str, str]]]:
        ws = self.wb['Rules'] if 'Rules' in self.wb.sheetnames else None
        if ws is None:
            return {}, {}
        headers = self._sheet_headers('Rules')
        concept_by_value: dict[str, str] = {}
        translations_by_concept: dict[str, dict[str, str]] = {}
        canonical_col = headers.get(canonical_header)
        if not canonical_col:
            return {}, {}
        for idx, row in self._iter_data_rows(ws, self._sheet_start_row('Rules')):
            canonical = self._cell(row, canonical_col)
            if not canonical:
                continue
            translations_by_concept.setdefault(canonical, {})
            concept_by_value[canonical] = canonical
            for lang_key, header in translations:
                col = headers.get(header)
                if not col:
                    continue
                val = self._cell(row, col)
                if val:
                    concept_by_value[val] = canonical
                    translations_by_concept[canonical][lang_key] = val
            translations_by_concept[canonical]['en'] = canonical
        return concept_by_value, translations_by_concept

    def validate(self):
        self.validate_required_sheets()
        self.validate_dictionary()
        self.validate_wertekatalog()
        self.validate_merkmalsgruppenkatalog()
        self.validate_klassen()
        self.validate_properties()
        self.validate_documents()
        self.validate_matrix()
        self.validate_concept_relations()
        self.validate_pipeline_minimums()
        return self.build_report()

    def validate_required_sheets(self):
        missing = [s for s in CORE_REQUIRED_SHEETS if s not in self.wb.sheetnames]
        for sheet in missing:
            self.add('error', 'missing_sheet', f'Missing required sheet: {sheet}', sheet=sheet)
        if missing:
            return
        unknown = [s for s in self.wb.sheetnames if s not in CORE_REQUIRED_SHEETS and s not in ALLOWED_OPTIONAL_SHEETS]
        for sheet in unknown:
            self.add('warning', 'unexpected_sheet', f'Unexpected sheet outside the current template family: {sheet}', sheet=sheet)

    def _dictionary_sheet_names(self) -> tuple[str, str | None]:
        return 'Header', 'Dictionary_public' if 'Dictionary_public' in self.wb.sheetnames else None

    def _dict_rows(self, sheet_name: str) -> dict[str, tuple[str | None, int]]:
        ws = self.wb[sheet_name]
        rows = {}
        for i, row in enumerate(ws.iter_rows(min_row=2, values_only=True), start=2):
            field = row[0] if len(row) > 0 else None
            value = row[1] if len(row) > 1 else None
            if field is None:
                continue
            field_text = str(field).strip()
            if not field_text:
                continue
            upper = field_text.upper()
            if set(field_text) <= {'─', '-', ' '}:
                continue
            if upper in {'IDENTIFICATION', 'GOVERNANCE', 'LEGEND', 'GOVERNANCE / PUBLISHING', 'DISCOVERY / CATALOG METADATA', 'DISTRIBUTION / ACCESS'}:
                continue
            rows[field_text] = (None if value is None else str(value).strip(), i)
        return rows

    def validate_dictionary(self):
        core_sheet, public_sheet = self._dictionary_sheet_names()
        core_rows = self._dict_rows(core_sheet)
        public_rows = self._dict_rows(public_sheet) if public_sheet else {}
        is_blank_template = self.workbook_path.name in {
            'Strukturvorlage_DataDictionary_empty.xlsx',
            'Strukturvorlage_DataDictionary_empty_public.xlsx',
            'Strukturvorlage_DataDictionary_empty_v0.9.5.xlsx',
            'Strukturvorlage_DataDictionary_empty_public_v0.9.5.xlsx',
        }

        for key in ['OrganizationCode', 'DictionaryName (EN)', 'DictionaryVersion', 'LifecycleStatus']:
            value_row = core_rows.get(key)
            if not value_row or not value_row[0]:
                level = 'warning' if is_blank_template else 'error'
                self.add(level, 'missing_dictionary_field', f'Erforderlicher Header-Wert fehlt: {key}', sheet=core_sheet, row=value_row[1] if value_row else None)

        org_code, org_row = core_rows.get('OrganizationCode', (None, None))
        if org_code and not re.match(r'^[A-Za-z]{1,7}$', org_code):
            self.add('error', 'invalid_organization_code', 'OrganizationCode must be a user-defined name using only letters (A-Z / a-z), max 7 characters.', sheet=core_sheet, row=org_row)

        name_en, name_en_row = core_rows.get('DictionaryName (EN)', (None, None))
        name_de, _ = core_rows.get('DictionaryName (DE)', (None, None))
        name_fr, _ = core_rows.get('DictionaryName (FR)', (None, None))
        name_it, _ = core_rows.get('DictionaryName (IT)', (None, None))
        if name_en and not any([name_de, name_fr, name_it]):
            self.add('error', 'missing_required_local_translation', 'Header.DictionaryName requires DictionaryName (EN) plus at least one local language in DE/FR/IT.', sheet=core_sheet, row=name_en_row)

        dictionary_code, code_row = core_rows.get('DictionaryCode', (None, None))
        expected_code = self.slugify(name_en).replace('-', '_') if name_en else None
        if expected_code and not dictionary_code:
            self.add_normalization(core_sheet, code_row or name_en_row, 'DictionaryCode', dictionary_code, expected_code, 'System-generated DictionaryCode derived from DictionaryName (EN)', 'derived-dictionary-code', True)
            dictionary_code = expected_code
        elif dictionary_code and expected_code and dictionary_code != expected_code:
            self.add('warning', 'system_generated_dictionary_code_override', f'DictionaryCode is a system-generated field. Manual value {dictionary_code} will be overwritten by generated value {expected_code}.', sheet=core_sheet, row=code_row)
            self.add_normalization(core_sheet, code_row, 'DictionaryCode', dictionary_code, expected_code, 'Manual DictionaryCode overridden by system-generated value derived from DictionaryName (EN)', 'derived-dictionary-code', True)
            dictionary_code = expected_code

        status = (core_rows.get('LifecycleStatus') or [None])[0]
        if status and status not in ALLOWED_LIFECYCLE:
            self.add('error', 'invalid_lifecycle', f'Invalid LifecycleStatus: {status}', sheet=core_sheet)
        version = (core_rows.get('DictionaryVersion') or [None])[0]
        if version and not SEMVER_RE.match(version):
            self.add('error', 'invalid_semver', f'DictionaryVersion must be semantic version, got: {version}', sheet=core_sheet)

        uri, uri_row = core_rows.get('DictionaryUri', (None, None))
        placeholder_uri = None
        if org_code and dictionary_code:
            placeholder_uri = f'https://example.com/{org_code}/{dictionary_code}'
        if not uri and placeholder_uri:
            self.add_normalization(
                core_sheet,
                uri_row or code_row or org_row,
                'DictionaryUri',
                uri,
                placeholder_uri,
                'Neutral pre-publication placeholder derived from OrganizationCode and DictionaryCode',
                'derived-dictionary-uri',
                True,
            )
        elif uri and not self.is_absolute_uri(uri):
            self.add('error', 'invalid_uri', f'DictionaryUri is not a valid absolute IRI: {uri}', sheet=core_sheet)
        elif uri:
            normalized_uri = uri.rstrip('/')
            parsed_uri = urlparse(normalized_uri)
            if parsed_uri.netloc == 'example.com':
                if placeholder_uri and normalized_uri != placeholder_uri:
                    self.add(
                        'warning',
                        'noncanonical_placeholder_dictionary_uri',
                        f'Pre-publication placeholder differs from the derived neutral URI {placeholder_uri}.',
                        sheet=core_sheet,
                        row=uri_row,
                    )
                    self.add_normalization(
                        core_sheet,
                        uri_row,
                        'DictionaryUri',
                        uri,
                        placeholder_uri,
                        'Neutral placeholder derived from OrganizationCode and DictionaryCode',
                        'canonical-placeholder-dictionary-uri',
                        True,
                    )
            elif parsed_uri.netloc == 'lindas.admin.ch':
                uri_version_match = re.search(r'/(\d+\.\d+\.\d+)$', normalized_uri)
                if not uri_version_match:
                    self.add(
                        'error',
                        'approved_lindas_uri_requires_version',
                        'An approved LINDAS DictionaryUri must end with the explicit semantic release version.',
                        sheet=core_sheet,
                        row=uri_row,
                    )
                elif version and uri_version_match.group(1) != version:
                    self.add(
                        'error',
                        'dictionary_uri_version_mismatch',
                        f'DictionaryUri version {uri_version_match.group(1)} does not match DictionaryVersion {version}.',
                        sheet=core_sheet,
                        row=uri_row,
                    )
            else:
                self.add(
                    'error',
                    'unsupported_dictionary_uri_authority',
                    'DictionaryUri must use the neutral example.com placeholder or an explicitly approved lindas.admin.ch URI.',
                    sheet=core_sheet,
                    row=uri_row,
                )

        i14y_uri, i14y_uri_row = core_rows.get('I14yDatasetUri', (None, None))
        if i14y_uri and (not self.is_absolute_uri(i14y_uri) or 'i14y.admin.ch/' not in i14y_uri):
            self.add('error', 'invalid_i14y_dataset_uri', 'I14yDatasetUri must be an absolute i14y.admin.ch dataset URI when supplied.', sheet=core_sheet, row=i14y_uri_row)

        if public_sheet:
            contact_email = (public_rows.get('ContactEmail') or [None])[0]
            if contact_email and '@' not in contact_email:
                self.add('warning', 'invalid_contact_email_public', f'ContactEmail in Dictionary_public is invalid: {contact_email}', sheet=public_sheet)
            primary_language = (public_rows.get('PrimaryLanguage') or [None])[0]
            if primary_language and not re.match(r'^[a-z]{2}(?:-[A-Z]{2})?$', primary_language):
                self.add('warning', 'invalid_primary_language_public', f'PrimaryLanguage in Dictionary_public should be ISO-like language tag (e.g. de or de-CH), got: {primary_language}', sheet=public_sheet)
